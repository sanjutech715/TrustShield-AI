"""
Pydantic schemas for TrustShield AI.

These models are the contract between the frontend and backend, and are
also what Gemini (when configured) is asked to fill in — the response
shape never changes based on which analyzer produced it, so the frontend
does not need to know or care whether AI ran.
"""

from __future__ import annotations

from typing import List, Literal, Optional

from pydantic import BaseModel, Field, field_validator

Language = Literal["en", "ta", "tanglish", "auto"]
RiskCategory = Literal["Low", "Medium", "High", "Critical"]
AnalyzerUsed = Literal["rule_based", "gemini"]


class AnalyzeRequest(BaseModel):
    message: str = Field(..., min_length=1, max_length=4000)
    language: Language = "auto"

    @field_validator("message")
    @classmethod
    def not_blank(cls, v: str) -> str:
        if not v.strip():
            raise ValueError("message cannot be blank")
        return v


class WarningSignal(BaseModel):
    id: str
    label: str
    category: str
    severity: Literal["low", "medium", "high"]
    matched_text: Optional[str] = None
    explanation: str


class AnalyzeResponse(BaseModel):
    risk_score: int = Field(..., ge=0, le=100)
    risk_category: RiskCategory
    signals: List[WarningSignal]
    summary: str
    recommended_actions: List[str]
    analyzer_used: AnalyzerUsed
    language_detected: Language
    disclaimer: str = (
        "This score is a heuristic indicator generated by pattern matching, "
        "not a calibrated probability and not proof of fraud. Always verify "
        "through an official channel before acting."
    )


class URLCheckRequest(BaseModel):
    url: str = Field(..., min_length=3, max_length=2048)


class URLIndicator(BaseModel):
    id: str
    label: str
    detail: str
    severity: Literal["low", "medium", "high"]


class URLCheckResponse(BaseModel):
    submitted_url: str
    hostname: Optional[str]
    scheme: Optional[str]
    indicators: List[URLIndicator]
    caution_level: RiskCategory
    disclaimer: str = (
        "TrustShield AI performs offline, pattern-based inspection of the "
        "URL text only. The link is never opened or visited, and no "
        "live threat-intelligence or safe-browsing service is queried. "
        "A clean result here CANNOT confirm that a site is safe, and a "
        "flagged result CANNOT confirm that it is malicious — verify "
        "through the official site or app before trusting it."
    )


class DashboardStats(BaseModel):
    total_scanned: int
    category_counts: dict
    recent: list
